-- Run against a disposable database after applying migrations.
-- All fixtures and assertions are rolled back.
begin;

insert into auth.users (id, email) values
  ('10000000-0000-0000-0000-000000000001', 'owner@example.com'),
  ('10000000-0000-0000-0000-000000000002', 'admin@example.com'),
  ('10000000-0000-0000-0000-000000000003', 'developer@example.com');

insert into public.orgs (id, name) values
  ('20000000-0000-0000-0000-000000000001', 'Platform'),
  ('20000000-0000-0000-0000-000000000002', 'Platform');

insert into public.members (org_id, user_id, role) values
  ('20000000-0000-0000-0000-000000000001', '10000000-0000-0000-0000-000000000001', 'owner'),
  ('20000000-0000-0000-0000-000000000001', '10000000-0000-0000-0000-000000000002', 'admin'),
  ('20000000-0000-0000-0000-000000000001', '10000000-0000-0000-0000-000000000003', 'developer'),
  ('20000000-0000-0000-0000-000000000002', '10000000-0000-0000-0000-000000000001', 'developer');

do $$
declare
  generated_id uuid;
  invalid_name text;
  invalid_role text;
begin
  assert (select array_agg(attname::text order by attnum) = array['id', 'name', 'deleted_at']
    from pg_attribute where attrelid = 'public.orgs'::regclass and attnum > 0 and not attisdropped),
    'Orgs must contain only id, name, and deleted_at';
  assert (select array_agg(attname::text order by attnum) = array['org_id', 'user_id', 'role']
    from pg_attribute where attrelid = 'public.members'::regclass and attnum > 0 and not attisdropped),
    'Members must contain only org_id, user_id, and role';

  insert into public.orgs (name) values ('Generated') returning id into generated_id;
  assert generated_id is not null, 'Org IDs must be generated by default';

  update public.orgs set name = repeat('名', 32) where id = generated_id;
  assert (select char_length(name) = 32 from public.orgs where id = generated_id),
    'Org names must accept 32 multibyte characters';

  foreach invalid_name in array array['', '   ', E'\t\n'] loop
    begin
      update public.orgs set name = invalid_name where id = generated_id;
      raise exception 'Blank org names must be rejected';
    exception when check_violation then null;
    end;
  end loop;

  begin
    update public.orgs set name = repeat('名', 33) where id = generated_id;
    raise exception 'Org names longer than 32 characters must be rejected';
  exception when string_data_right_truncation then null;
  end;

  begin
    update public.orgs set name = null where id = generated_id;
    raise exception 'Null org names must be rejected';
  exception when not_null_violation then null;
  end;

  begin
    insert into public.orgs (id, name) values (generated_id, 'Duplicate');
    raise exception 'Duplicate org IDs must be rejected';
  exception when unique_violation then null;
  end;

  assert (select count(*) = 3 from public.members
    where org_id = '20000000-0000-0000-0000-000000000001'),
    'An org must support owner, admin, and developer members';
  assert (select count(*) = 2 from public.members
    where user_id = '10000000-0000-0000-0000-000000000001'),
    'A user must be able to join multiple orgs with different roles';

  begin
    insert into public.members (org_id, user_id, role) values
      ('20000000-0000-0000-0000-000000000001', '10000000-0000-0000-0000-000000000001', 'admin');
    raise exception 'Duplicate org memberships must be rejected';
  exception when unique_violation then null;
  end;

  foreach invalid_role in array array['super_admin', 'dev', 'user', '', 'Owner'] loop
    begin
      update public.members set role = invalid_role
        where org_id = '20000000-0000-0000-0000-000000000001'
          and user_id = '10000000-0000-0000-0000-000000000001';
      raise exception 'Unsupported member roles must be rejected';
    exception when check_violation then null;
    end;
  end loop;

  begin
    insert into public.members (org_id, user_id) values
      ('20000000-0000-0000-0000-000000000002', '10000000-0000-0000-0000-000000000002');
    raise exception 'Member roles must be supplied, not defaulted';
  exception when not_null_violation then null;
  end;

  begin
    update public.members set role = null
      where org_id = '20000000-0000-0000-0000-000000000001'
        and user_id = '10000000-0000-0000-0000-000000000001';
    raise exception 'Null member roles must be rejected';
  exception when not_null_violation then null;
  end;

  begin
    insert into public.members (org_id, user_id, role) values
      ('20000000-0000-0000-0000-000000000099', '10000000-0000-0000-0000-000000000001', 'developer');
    raise exception 'Members must reference an existing org';
  exception when foreign_key_violation then null;
  end;

  begin
    insert into public.members (org_id, user_id, role) values
      ('20000000-0000-0000-0000-000000000001', '10000000-0000-0000-0000-000000000099', 'developer');
    raise exception 'Members must reference an existing auth user';
  exception when foreign_key_violation then null;
  end;

  begin
    insert into public.members (user_id, role) values
      ('10000000-0000-0000-0000-000000000001', 'developer');
    raise exception 'Null org IDs must be rejected';
  exception when not_null_violation then null;
  end;

  begin
    insert into public.members (org_id, role) values
      ('20000000-0000-0000-0000-000000000001', 'developer');
    raise exception 'Null user IDs must be rejected';
  exception when not_null_violation then null;
  end;

  assert (select relrowsecurity from pg_class where oid = 'public.orgs'::regclass),
    'Orgs must enable RLS';
  assert (select relrowsecurity from pg_class where oid = 'public.members'::regclass),
    'Members must enable RLS';
end;
$$;

-- RLS must deny direct reads even when API roles have table privileges.
grant select on public.orgs, public.members to anon, authenticated;

set local role anon;
do $$
begin
  assert not exists (select from public.orgs), 'Anonymous users must not read orgs';
  assert not exists (select from public.members), 'Anonymous users must not read members';
end;
$$;

set local role authenticated;
do $$
begin
  assert not exists (select from public.orgs), 'Authenticated users must not read orgs directly';
  assert not exists (select from public.members), 'Authenticated users must not read members directly';
end;
$$;

reset role;
rollback;
